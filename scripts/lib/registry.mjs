// Reading the Theme directories and rendering what the build writes from them.
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

/** Every Theme directory under `<root>/themes`, in directory order with `default` first. */
export function loadThemes(root) {
  const dir = join(root, "themes");
  const ids = readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory())
    .sort((a, b) => (a === "default" ? -1 : b === "default" ? 1 : a < b ? -1 : a > b ? 1 : 0));
  return ids.map((id) => {
    const path = join(dir, id);
    const manifestPath = join(path, "theme.json");
    const cssPath = join(path, "theme.css");
    return {
      id,
      path,
      manifest: existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : null,
      css: existsSync(cssPath) ? readFileSync(cssPath, "utf8") : null,
      files: listFiles(path),
    };
  });
}

/** Every file under `dir`, as paths relative to it with `/` separators. */
export function listFiles(dir, prefix = "") {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    const rel = prefix ? `${prefix}/${name}` : name;
    return statSync(full).isDirectory() ? listFiles(full, rel) : [rel];
  });
}

const HEADER = "/* Generated by dyeworks scripts/build.mjs from the repository's sources; do not edit. */\n";

/** `tokens.css`: every contract default on `:root`, so a page without a Theme renders as `default` light. */
export function renderTokensCss(contract) {
  const lines = contract.tokens.map((t) => `  ${t.name}: ${t.default};`);
  return `${HEADER}:root {\n  color-scheme: light;\n${lines.join("\n")}\n}\n`;
}

/** `themes.css`: every Theme file, in registry order. */
export function renderThemesCss(themes) {
  return HEADER + themes.map((t) => `\n/* themes/${t.id}/theme.css */\n${t.css.trim()}\n`).join("");
}

/** The registry entry of a Theme: its manifest's fields, in the manifest's order. */
export function registryEntry(theme) {
  const { id, label, schemes, intensity, assets } = theme.manifest;
  return { id, label, schemes, intensity, assets };
}

/** `registry.js`: the generated module exporting `themes` and `options()`. */
export function renderRegistry(themes) {
  const entries = themes.map(registryEntry);
  return `// Generated by dyeworks scripts/build.mjs from the Theme directories; do not edit.

/** Every Theme, in directory order with \`default\` first. */
export const themes = ${JSON.stringify(entries, null, 2)};

/** The menu options: one per single-Scheme Theme; auto, light and dark for a Theme with both. */
export function options() {
  return themes.flatMap((t) =>
    t.schemes.length === 1
      ? [{ theme: t.id, scheme: t.schemes[0], label: t.label }]
      : ["auto", "light", "dark"].map((scheme) => ({ theme: t.id, scheme, label: \`\${t.label} · \${scheme}\` })),
  );
}
`;
}

/** `registry.d.ts`: the types of the generated module, kept beside the sources in `src/registry.d.ts`. */
export function renderRegistryTypes() {
  return readFileSync(new URL("../../src/registry.d.ts", import.meta.url), "utf8");
}

/** `tokens.js`: the contract's Token names, for the Contract check. */
export function renderTokenNames(contract) {
  return `// Generated by dyeworks scripts/build.mjs from tokens.json; do not edit.\nexport const tokenNames = ${JSON.stringify(contract.tokens.map((t) => t.name))};\n`;
}

/** `tokens.d.ts`: its types, kept beside the sources in `src/tokens.d.ts`. */
export function renderTokenNamesTypes() {
  return readFileSync(new URL("../../src/tokens.d.ts", import.meta.url), "utf8");
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** The contract's reference page: every Token and every Slot kind, from the two machine-readable lists. */
export function renderReference(contract, slots) {
  const tokenRows = contract.tokens
    .map((t) => `      <tr><td><code>${esc(t.name)}</code></td><td>${esc(t.tier)}</td><td>${esc(t.type)}</td><td>${esc(t.meaning)}</td><td><code>${esc(t.default)}</code></td></tr>`)
    .join("\n");
  const slotRows = slots.slots
    .map((s) => `      <tr><td><code>${esc(s.kind)}</code></td><td>${s.reads.map((r) => `<code>${esc(r)}</code>`).join(", ")}</td><td>${esc(s.treatment)}</td></tr>`)
    .join("\n");
  return `<!doctype html>
<!-- Generated by dyeworks scripts/build.mjs from tokens.json and slots.json; do not edit. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>dyeworks: the Token contract</title>
  <link rel="stylesheet" href="./tokens.css">
  <style>
    body { margin: 2rem auto; max-width: 72rem; padding: 0 1.5rem; background: var(--bg); color: var(--fg); font-family: var(--font-sans); line-height: 1.5; }
    table { border-collapse: collapse; width: 100%; margin-bottom: 2rem; }
    th, td { text-align: left; vertical-align: top; padding: 0.4rem 0.6rem; border-bottom: 1px solid var(--border); }
    th { color: var(--muted); font-weight: 600; }
    code { font-family: var(--font-mono); font-size: 0.9em; }
  </style>
</head>
<body>
  <h1>The Token contract</h1>
  <p>Format <code>${esc(contract.format)}</code>; Schemes ${contract.schemes.map((s) => `<code>${esc(s)}</code>`).join(", ")}. The default is the value the <code>default</code> Theme uses in its light Scheme.</p>
  <table>
    <thead><tr><th>Token</th><th>Tier</th><th>Type</th><th>Meaning</th><th>Default</th></tr></thead>
    <tbody>
${tokenRows}
    </tbody>
  </table>
  <h2>The Slot vocabulary</h2>
  <p>Format <code>${esc(slots.format)}</code>. <code>slots.css</code> implements each treatment on <code>[data-slot="&lt;kind&gt;"]</code>.</p>
  <table>
    <thead><tr><th>Kind</th><th>Reads</th><th>Treatment</th></tr></thead>
    <tbody>
${slotRows}
    </tbody>
  </table>
</body>
</html>
`;
}
